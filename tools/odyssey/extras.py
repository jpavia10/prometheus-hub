#!/usr/bin/env python3
"""Odyssey extras (2026-11-23): the day-by-day logs and the landmarks, from Gemini's Nov 21 photo work, for the trip dossiers.

Inputs (Gemini's files, scored #128, #129 and #130 in collaborators/CONTRIBUTOR_SCORES.md):
  odyssey_gemini_eurotrip-days_*.json        one row per day with photos, Jul-Sep 2015
  odyssey_gemini_philippines-days_*.json     one row per day on both 2024 trips
  odyssey_gemini_landmarks_*.json            65 landmarks with coordinates, an official page and a quoted fact
  odyssey_gemini_photo-trip-days_*.json      (2026-11-23, run 6, scored #139) the ten photo trips day by day
  odyssey_gemini_landmarks-usa_*.json        (2026-11-23, run 6, scored #158) 24 landmarks in those trips' photos
  odyssey_gemini_new-trip-days_*.json        (2026-11-24, run 7, scored #196) the six newer photo trips day by day (two places
                                             corrected by Claude from the pictures: Long Beach on 2015-03-06, Lambertville on 2022-09-15)
  odyssey_gemini_landmarks-new_*.json        (2026-11-24, run 7) 14 landmarks; Claude kept 10 and filed each under its own trip
A day belongs to the trip whose dates (odyssey-data.js) hold it; a file with 'landmarks' in its name is a landmark list.

Output: pillars/odyssey/odyssey-extra.js
  window.ODYSSEY_DAYS      = {trip id: [{d, c, p, n, t0, t1}]}   only the trip's own dates; no file ids, no GPS
  window.ODYSSEY_LANDMARKS = [{name, local, city, country, lat, lon, year, unesco, url, fact, trips: [trip ids]}]
A landmark belongs to every trip with a stop within 130 km of it (Manila's sights show on both Philippine trips), unless its row names
its trips itself ("trips": [trip ids]; 2026-11-24: the run-7 landmarks were each seen in one trip's photos, so Endeavour is not filed
under the 2019 cruise out of Long Beach). A name already listed is not added twice.

Notes are shipped as Gemini wrote them (owner, 2026-11-23: privacy is not a limit in Odyssey while building), tidied for reading:
GPS readings in brackets and time-zone remarks are dropped as clutter; Drive file ids are not shipped (nothing reads them).

  python3 tools/odyssey/extras.py EUROTRIP_DAYS PHILIPPINES_DAYS LANDMARKS [PHOTO_TRIP_DAYS LANDMARKS_USA ...]
"""
import json, math, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "pillars", "odyssey", "odyssey-extra.js")


def clean(t):
    t = re.sub(r"\s*\((?:EXIF )?GPS[^)]*\)", "", t)                        # coordinates in brackets read as clutter
    t = re.sub(r"\s*\((?:EDT|EST|PDT|PST) timestamp\)", "", t)
    t = re.sub(r"\s{2,}", " ", t).strip(" ;")
    return t[:1].upper() + t[1:]


def seeds():
    js = "global.window={};require(process.argv[1]);process.stdout.write(JSON.stringify(window.ODYSSEY_DATA.seedTrips))"
    return json.loads(subprocess.check_output(["node", "-e", js, os.path.join(HERE, "..", "..", "pillars", "odyssey", "odyssey-data.js")]))


def km(a, b):
    f = math.pi / 180; dl = (b[0] - a[0]) * f; dn = (b[1] - a[1]) * f
    h = math.sin(dl / 2) ** 2 + math.cos(a[0] * f) * math.cos(b[0] * f) * math.sin(dn / 2) ** 2
    return 2 * 6371 * math.asin(math.sqrt(h))


def main(*paths):
    trips = seeds(); SPANS = {t["id"]: (t["start"], t["end"]) for t in trips}
    days = {k: [] for k in SPANS}
    for path in (p for p in paths if "landmarks" not in os.path.basename(p)):
        for r in json.load(open(path)):
            for tid, (a, b) in SPANS.items():
                if a <= r["date"] <= b:
                    row = {"d": r["date"], "c": clean(r["city"]), "p": clean(r["places"]), "n": r.get("photos")}
                    if r.get("first_time"): row["t0"] = r["first_time"]
                    if r.get("last_time"): row["t1"] = r["last_time"]
                    days[tid].append(row)
    for v in days.values(): v.sort(key=lambda x: x["d"])
    days = {k: v for k, v in days.items() if v}
    marks = []
    for r in (r for p in paths if "landmarks" in os.path.basename(p) for r in json.load(open(p))):
        if any(m["name"] == r["name"] for m in marks): continue
        near = r.get("trips") or [t["id"] for t in trips if any(km((r["lat"], r["lon"]), (l["lat"], l["lon"])) <= 130
                                                                for l in t.get("legs", []) if not l.get("home") and "lat" in l)]
        marks.append({"name": r["name"], "local": r.get("local_name") if r.get("local_name") != r["name"] else "", "city": r["city"],
                      "country": r["country"], "lat": r["lat"], "lon": r["lon"], "year": r.get("year", ""),
                      "unesco": r.get("unesco") if r.get("unesco") not in ("no", "", None) else "", "url": r["url"], "fact": r["fact"], "trips": near})
    lost = [m["name"] for m in marks if not m["trips"]]
    with open(OUT, "w") as f:
        f.write("/* Odyssey extras, generated by tools/odyssey/extras.py from Gemini's photo work (Nov 21, scored #128-#130; Nov 23, #139 and #158; Nov 24, #196): each trip day by day\n"
                "   from the photos, and the landmarks in them with a fact from each one's official page. Not second-read yet. Do not edit by hand. */\n")
        f.write("window.ODYSSEY_DAYS = " + json.dumps(days, ensure_ascii=False, separators=(",", ":")) + ";\n")
        f.write("window.ODYSSEY_LANDMARKS = " + json.dumps(marks, ensure_ascii=False, separators=(",", ":")).replace('},{', '},\n{') + ";\n")
    print({k: len(v) for k, v in days.items()}, len(marks), "landmarks; on no trip:", lost)


if __name__ == "__main__":
    main(*sys.argv[1:])
