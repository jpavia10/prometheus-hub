#!/usr/bin/env python3
"""Odyssey's travel globe (2026-11-23): the world's coastlines for the stage at the top of the page (pillars/odyssey/stage.js).

Source: Natural Earth 1:110m land (public domain), as packaged in world-atlas@2.0.2 (land-110m.json, TopoJSON). Each ring is
simplified (Douglas-Peucker, 0.45 degrees) and written as a flat list of whole tenths of a degree, [lon, lat, lon, lat, ...].

  python3 tools/odyssey/globe.py path/to/land-110m.json
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from basemap import decode, ring, dp_ring, area  # noqa: E402


def main(src, dst):
    topo = json.load(open(src)); arcs = decode(topo); rings = []
    for g in topo["objects"]["land"]["geometries"]:
        polys = [g["arcs"]] if g["type"] == "Polygon" else g["arcs"] if g["type"] == "MultiPolygon" else []
        for poly in polys:
            r = ring(arcs, poly[0])                               # outer ring only: lakes are not drawn at this size
            if area(r) < 1.5: continue                            # islands under ~1.5 square degrees drop out
            r = dp_ring(r, 0.45)
            if len(r) >= 4: rings.append([v for lon, lat in r for v in (round(lon * 10), round(lat * 10))])
    with open(dst, "w") as f:
        f.write("/* Odyssey globe coastlines, generated by tools/odyssey/globe.py from Natural Earth 1:110m land (public domain, world-atlas@2.0.2):\n"
                "   one flat [lon, lat, ...] list per ring in tenths of a degree. Do not edit by hand. */\n")
        f.write("window.ODYSSEY_GLOBE = " + json.dumps(rings, separators=(",", ":")) + ";\n")
    print(len(rings), "rings,", sum(len(r) // 2 for r in rings), "points,", os.path.getsize(dst), "bytes")


if __name__ == "__main__":
    main(sys.argv[1], os.path.join(HERE, "..", "..", "pillars", "odyssey", "globe.js"))
