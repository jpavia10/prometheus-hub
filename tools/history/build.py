#!/usr/bin/env python3
"""World history for every pillar (Claude, 2026-11-24; owner: "Athenaeum can has supplemental world history on it already so we can refine
and expand that then use it as a dataset for other pillars use ... no reason to generate it when it can be higher quality and denser for
the more recent periods of time").

The master is pillars/athenaeum/data/world-history.json. This script checks every entry and writes what is derived from it:
  pillars/athenaeum/data/world-history.js         window.PK_HISTORY, for any page (kit/history.js reads it)
  pillars/athenaeum/data/cause-event-consequence.json   Athenaeum's chronicle (the entries that carry a cause -> event -> consequence chain)
  pillars/athenaeum/data/history-coverage.json    entries per century and per region, so the gaps are visible

    python3 tools/history/build.py            write
    python3 tools/history/build.py --check    exit 1 if an entry is invalid or a derived file is out of date (CI)
"""
import json, os, re, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "pillars/athenaeum/data")
MASTER = os.path.join(D, "world-history.json")
REGIONS = {"world", "europe", "united-states", "american-colonies", "lithuania", "russian-empire", "poland", "malta", "italy", "michigan", "detroit", "new-york", "massachusetts",
           "tennessee", "north-carolina", "south-carolina", "virginia", "pennsylvania", "georgia", "ohio", "california", "england", "scotland", "ireland", "canada", "ontario",
           "france", "germany", "mediterranean", "mesopotamia", "greece", "rome", "byzantium", "anatolia", "middle-east", "china", "japan", "south-asia", "mesoamerica",
           "caribbean", "africa", "philippines", "cherokee-nation"}
THEMES = {"war", "disease", "economy", "politics", "climate", "technology", "migration", "law", "labor", "religion", "society", "industry", "culture"}
PREC = {"day", "month", "year", "decade", "century"}

def year(d): m = re.match(r"^(-?\d{1,4})", str(d or "")); return int(m.group(1)) if m else None

def check(H):
    bad, ids = [], set()
    for x in H["entries"]:
        i = x.get("id"); w = lambda m: bad.append(f"{i}: {m}")
        if not i or i in ids: w("missing or repeated id")
        ids.add(i)
        if year(x.get("date")) is None: w("no date")
        if x.get("precision") not in PREC: w(f"precision {x.get('precision')!r}")
        if x["precision"] == "day" and not re.match(r"^\d{4}-\d{2}-\d{2}$", x["date"]): w("precision day needs YYYY-MM-DD")
        if not x.get("title") or not x.get("text"): w("title and text are required")
        for r in x.get("regions") or []:
            if r not in REGIONS: w(f"unknown region {r}")
        if not x.get("regions"): w("no region")
        for t in x.get("themes") or []:
            if t not in THEMES: w(f"unknown theme {t}")
        for s in x.get("sources") or []:
            if s.get("url") and not str(s["url"]).startswith("https://"): w("a source url that is not https")
        if x.get("check", "").startswith("sourced") and not any(s.get("url") for s in x.get("sources") or []): w("marked sourced without a source url")
        p = x.get("place")
        if p and (not isinstance(p.get("lat"), (int, float)) or not isinstance(p.get("lon"), (int, float))): w("place without numeric lat/lon")
    return bad

def derive(H):
    ents = sorted(H["entries"], key=lambda x: (year(x["date"]), x["date"]))
    js = ("/* generated by tools/history/build.py from world-history.json: edit the JSON, not this file */\n"
          "window.PK_HISTORY = " + json.dumps({"schema": H["schema"], "asOf": H["asOf"], "entries": ents}, ensure_ascii=False, separators=(",", ":")) + ";\n")
    cp = H.get("chronicle_pack") or {}
    chron = [x for x in H["entries"] if x.get("chain")]
    chron.sort(key=lambda x: x.get("order", 10**6))
    out = []
    for x in chron:
        s0 = (x.get("sources") or [{}])[0]; dating = next((s for s in x.get("sources") or [] if s.get("cite", "").startswith("the dating")), None)
        e = {"id": x["id"], "name": x["title"], "civilization": x.get("civilization") or ", ".join(x["regions"]), "date": x.get("written") or str(x["date"]),
             "cause": x["chain"]["cause"], "event": x["chain"]["event"], "consequence": x["chain"]["consequence"],
             "source": (s0.get("cite") or "") + (" — " + s0["url"] if s0.get("url") else ""), "evidence_quotes": x.get("quotes") or ([s0["quote"]] if s0.get("quote") else [])}
        if x.get("place"): e["where"] = x["place"]
        span = {"start": year(x["date"]), "end": year(x["end"]) if x.get("end") else year(x["date"])}
        if x.get("note"): span["note"] = x["note"]
        if dating and dating.get("url"): span["url"] = dating["url"]
        e["span"] = span; out.append(e)
    chronicle = {"pack": cp.get("pack"), "asOf": cp.get("asOf"), "notes": cp.get("notes", []), "entries": out}
    cov = {"asOf": H["asOf"], "total": len(ents), "sourced": sum(1 for x in ents if x.get("check", "").startswith("sourced") or x.get("check", "").startswith("checked")),
           "by_century": dict(sorted(collections.Counter(f"{(year(x['date']) // 100) * 100}s" for x in ents).items(), key=lambda kv: int(kv[0][:-1]))),
           "by_region": dict(collections.Counter(r for x in ents for r in x["regions"]).most_common())}
    return {"world-history.js": js, "cause-event-consequence.json": json.dumps(chronicle, ensure_ascii=False, indent=1) + "\n",
            "history-coverage.json": json.dumps(cov, ensure_ascii=False, indent=1) + "\n"}

def main():
    H = json.load(open(MASTER)); bad = check(H)
    if bad: print("invalid entries:\n  " + "\n  ".join(bad)); sys.exit(1)
    out = derive(H); stale = []
    for name, text in out.items():
        p = os.path.join(D, name); cur = open(p).read() if os.path.exists(p) else None
        if cur != text:
            stale.append(name)
            if "--check" not in sys.argv: open(p, "w").write(text)
    if "--check" in sys.argv and stale: print("out of date: " + ", ".join(stale) + " (run tools/history/build.py)"); sys.exit(1)
    cov = json.loads(out["history-coverage.json"])
    print(f"history: {cov['total']} entries, {cov['sourced']} sourced; " + ("wrote " + ", ".join(stale) if stale and "--check" not in sys.argv else "up to date"))

if __name__ == "__main__":
    main()
