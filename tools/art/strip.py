#!/usr/bin/env python3
"""The menu's level strip as painted cards (2026-11-23, owner: the homes are "cool but need refinement").

One sprite sheet of every painted world (art/worlds/world_{id}.webp), each cut to a 3:4 card around its subject and lightly
sharpened, so the strip under the menu shows the paintings instead of 27 line icons. One file, one request, cached offline.

  python3 tools/art/strip.py        -> art/worlds/strip.webp + art/worlds/strip.json ({"w", "h", "ids": [...]}, card i at x = i * w)
"""
import json, os
from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, "..", ".."); W = os.path.join(ROOT, "art", "worlds")
CW, CH = 96, 128                                       # card size in the sheet: 48 x 64 css px at 2x
FOCUS = {"kairos": 0.42, "garage": 0.47, "odyssey": 0.46, "selling": 0.56, "kin": 0.56, "continuity": 0.6, "hearth": 0.4, "money": 0.5,
         "hermes": 0.46, "piano": 0.42, "bastion": 0.42, "privacy": 0.38, "games": 0.38, "forge": 0.43, "foundry": 0.42, "observatory": 0.42, "mythos": 0.39}   # as in kit/world.js


def card(path, fy):
    im = Image.open(path).convert("RGB"); w, h = im.size
    cw = int(w * 0.62); ch = int(cw * CH / CW)         # the middle of the painting, where its subject stands
    x0 = (w - cw) // 2; y0 = max(0, min(h - ch, int(h * fy - ch / 2)))
    c = im.crop((x0, y0, x0 + cw, y0 + ch)).resize((CW, CH), Image.LANCZOS)
    return c.filter(ImageFilter.UnsharpMask(radius=1.2, percent=60, threshold=2))


def main():
    ids = [i for i in json.load(open(os.path.join(W, "index.json")))["worlds"] if os.path.exists(os.path.join(W, f"world_{i}.webp"))]
    sheet = Image.new("RGB", (CW * len(ids), CH))
    for k, i in enumerate(ids): sheet.paste(card(os.path.join(W, f"world_{i}.webp"), FOCUS.get(i, 0.46)), (k * CW, 0))
    sheet.save(os.path.join(W, "strip.webp"), "WEBP", quality=72, method=6)
    json.dump({"about": "Generated by tools/art/strip.py: one 3:4 card per painted world, card i at x = i * w.", "w": CW, "h": CH, "ids": ids},
              open(os.path.join(W, "strip.json"), "w"), indent=1)
    print(len(ids), "cards,", os.path.getsize(os.path.join(W, "strip.webp")), "bytes")


if __name__ == "__main__":
    main()
