#!/usr/bin/env python3
"""Prometheus homework renderer (Claude, 2026-11-05; owner: "I can ask do you have homework and it checks each folder for each pillar").

Every pillar keeps its homework in docs/agents/queues.json (in its own repo, or under pillars/{id}/ here until it has one). This script:
  1. writes each pillar's docs/agents/QUEUE_{ai}.md (one page per AI, every AI, even when it has nothing there: predictable),
  2. writes HOMEWORK.md here (the board: every pillar x every AI) and data/board.json (the desk reads it),
  3. writes docs/agents/drive/HOMEWORK_{ai}.txt (the text of each AI's Drive doc 'HOMEWORK — {Name} (every pillar)') and
     docs/agents/drive/{pillar}/README.txt (the text of 'Prometheus Hub/Pillars/{Pillar}/README — {Pillar}': what it is + each AI's list).
Titan Reliquary keeps its own research loop; its open assignments are counted from its QUEUE_{ai}.md.

    python3 tools/kit/render.py [--root /home/user]     repos are found as {root}/{repo name}; default: the folder above this repo
    python3 tools/kit/render.py --check                  exit 1 if any rendered file is out of date (CI)
"""
import json, os, re, sys, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
HUB = os.path.dirname(os.path.dirname(HERE))
GEN = "<!-- generated by jpavia10/prometheus-hub tools/kit/render.py from docs/agents/queues.json: edit the JSON, not this page -->"
DRIVE_ROOT = "Prometheus Hub/Pillars/{name}/"
GH = "https://github.com/{repo}/blob/main/{path}"
RAW = "https://raw.githubusercontent.com/{repo}/main/{path}"


def load(p):
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def pillar_dir(p, root):
    if p.get("repo") and p["id"] != "hub":
        d = os.path.join(root, p["repo"].split("/")[1])
        return d if os.path.isdir(d) else None
    return os.path.join(HUB, p["home"]) if p.get("home") else HUB


def queue_path(p):
    """(repo, path inside it) of the pillar's queues.json."""
    if p.get("home"):
        return "jpavia10/prometheus-hub", p["home"] + "/docs/agents/queues.json"
    return p["repo"], "docs/agents/queues.json"


def open_tasks(q, ai):
    for a in q.get("agents", []):
        if a["id"] == ai:
            return [t for t in a.get("tasks", []) if t.get("state") in ("now", "next")]
    return []


def task_md(i, t, p, folder):
    L = [f"## {i}. {t['id']} · {t['title']}", "", f"**Due:** {t.get('due', '-')} · **State:** {t.get('state')}" + (" (starts when the file it checks is in the folder)" if t.get("state") == "next" else ""), ""]
    if t.get("why"): L += [f"**Why:** {t['why']}", ""]
    if t.get("inputs"): L += ["**Read first:**"] + [f"- {x}" for x in t["inputs"]] + [""]
    if t.get("steps"): L += ["**Do this:**"] + [f"{n}. {s}" for n, s in enumerate(t["steps"], 1)] + [""]
    d = t.get("deliver") or {}
    if d:
        L += [f"**Make:** `{d.get('file')}`", "", f"**Save in:** {d.get('folder')}", ""]
        if d.get("shape"): L += [f"**Shape:** `{d['shape']}`", ""]
    if t.get("count"): L += [f"**How many:** {t['count']}", ""]
    if t.get("done_when"): L += [f"**Done when:** {t['done_when']}", ""]
    if t.get("checks"): L += ["**How Claude checks it:**"] + [f"- {x}" for x in t["checks"]] + [""]
    if t.get("rejected_if"): L += ["**Not done (sent back) if:**"] + [f"- {x}" for x in t["rejected_if"]] + [""]
    return L


def queue_page(p, ai, tasks, stamp):
    folder = DRIVE_ROOT.format(name=p["name"]) + "incoming (AI drop files)/"
    start = GH.format(repo="jpavia10/prometheus-hub", path="AI_START_HERE.md")
    L = [GEN, "", f"# {p['name']} · homework for {ai['name']}", "",
         f"Updated {stamp} · {len(tasks)} open · Rules for every pillar: {start}. Your homework in every pillar on one page: Drive doc 'Prometheus Hub/{ai['drive_folder']}/HOMEWORK — {ai['name']} (every pillar)'.", ""]
    if not tasks:
        L += [f"No homework for {ai['name']} in {p['name']} right now. Check your HOMEWORK doc for the other pillars.", ""]
    for i, t in enumerate(sorted(tasks, key=lambda t: (t.get("state") != "now", t.get("due", "9"))), 1):
        L += task_md(i, t, p, folder)
    return "\n".join(L).rstrip() + "\n"


def drive_queue(p, ai, tasks, stamp):
    """The Drive doc 'Prometheus Hub/Pillars/{Pillar}/WORK QUEUE — {Name}': the list; the full text of every task is in the AI's HOMEWORK doc."""
    L = [f"WORK QUEUE — {ai['name']} · {p['name']}", "", f"Updated {stamp} · {len(tasks)} open in this pillar.", "",
         f"The full instructions for every task below (what to read, what to make, how many, how it is checked) are in your Drive doc "
         f"'Prometheus Hub/{ai['drive_folder']}/HOMEWORK — {ai['name']} (every pillar)', in the order to do them. "
         f"Save what you make in this folder's 'incoming (AI drop files)'.", ""]
    if not tasks:
        L += [f"No homework for {ai['name']} in {p['name']} right now."]
    for t in sorted(tasks, key=lambda t: (t.get("state") != "now", t.get("due", "9"))):
        d = t.get("deliver") or {}
        L += [f"- {t['id']} · {t['title']} · due {t.get('due')}" + (" · waits for its input file" if t.get("state") == "next" else ""),
              f"    make: {d.get('file')} · how many: {t.get('count')} · done when: {t.get('done_when')}"]
    return "\n".join(L).rstrip() + "\n"


def titan_count(root, ai):
    """Open Titan assignments and projects for one AI, from its own QUEUE page (Titan's loop writes it)."""
    f = os.path.join(root, "titan-reliquary-preview", "docs", "agents", f"QUEUE_{ai}.md")
    if not os.path.exists(f):
        return None
    s = open(f, encoding="utf-8").read()
    hw = len(re.findall(r"^(?:- |### )\d+\. HW-", s, re.M))          # compact pages list sheets as '- 1. HW-', full ones as '### 1. HW-'
    proj = len(re.findall(r"^### (?!\d+\. HW-)", s, re.M))
    return hw, proj


def main(argv):
    root = argv[argv.index("--root") + 1] if "--root" in argv else os.path.dirname(HUB)
    check = "--check" in argv
    reg = load(os.path.join(HUB, "pillars.json"))
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC") if not check else None
    out = {}            # path -> text
    board = {"updated": None, "pillars": []}
    per_ai = {a["id"]: [] for a in reg["ais"]}
    deadlines = []
    drive_parts = {}    # pillar id -> (pillar, [each AI's section]) = the Drive doc 'README — {Pillar}' 
    for p in reg["pillars"]:
        row = {"id": p["id"], "name": p["name"], "state": p["state"], "live": p.get("live", ""), "open": {}}
        if p.get("paused"):
            board["pillars"].append(row); continue
        if p.get("own_loop"):
            for a in reg["ais"]:
                c = titan_count(root, a["id"])
                row["open"][a["id"]] = (c[0] + c[1]) if c else None
                if c and (c[0] + c[1]):
                    per_ai[a["id"]].append((p, None, c))
            board["pillars"].append(row); continue
        d = pillar_dir(p, root)
        qf = d and os.path.join(d, "docs", "agents", "queues.json")
        if not qf or not os.path.exists(qf):
            board["pillars"].append(row); continue
        q = load(qf)
        for a in reg["ais"] + [{"id": "claude", "name": "Claude", "drive_folder": "Claude"}]:
            tasks = open_tasks(q, a["id"])
            row["open"][a["id"]] = len(tasks)
            for t in tasks:     # every open task with its due date: Kairos Meridian shows them on the calendar
                deadlines.append({"due": t.get("due"), "pillar": p["id"], "pillar_name": p["name"], "ai": a["id"], "ai_name": a["name"],
                                  "id": t["id"], "title": t["title"], "state": t.get("state"), "count": t.get("count")})
            if a["id"] == "claude":
                continue
            out[os.path.join(d, "docs", "agents", f"QUEUE_{a['id']}.md")] = queue_page(p, a, tasks, stamp or "{stamp}")
            drive_parts.setdefault(p["id"], (p, []))[1].append(drive_queue(p, a, tasks, stamp or "{stamp}"))
            for t in tasks:
                per_ai[a["id"]].append((p, t, None))
        board["pillars"].append(row)

    for pid, (p, parts) in drive_parts.items():
        live = p.get("live") or "no page yet"
        repo = p.get("repo") or f"jpavia10/prometheus-hub, folder {p.get('home')}/ (until it has its own repo)"
        head = [f"README — {p['name']}", "", f"{p['what']}", "", f"Live: {live} · Code and rules: https://github.com/{repo.split(',')[0]} · State: {p['state']}" + (" · PRIVATE: made-up data or public research only" if p.get("private") else ""), "",
                "Rules for every pillar: https://github.com/jpavia10/prometheus-hub/blob/main/AI_START_HERE.md. Save what you make in this folder's 'incoming (AI drop files)' under the exact name your task gives. "
                "Each AI's section below lists its homework here; the full instructions for each task are in that AI's own doc 'Prometheus Hub/{AI folder}/HOMEWORK — {Name} (every pillar)'.", ""]
        body = []
        for part in parts:
            lines = part.splitlines()
            body += ["## " + lines[0].replace("WORK QUEUE — ", "").split(" · ")[0]] + [l for l in lines[1:] if not l.startswith("The full instructions")] + [""]
        out[os.path.join(HUB, "docs", "agents", "drive", pid, "README.txt")] = "\n".join(head + body).rstrip() + "\n"

    # each AI's one page for every pillar
    for a in reg["ais"]:
        items = per_ai[a["id"]]
        titan = [x for x in items if x[1] is None]
        work = sorted([x for x in items if x[1] is not None], key=lambda x: (x[1].get("state") != "now", x[1].get("due", "9")))
        n = len(work) + sum(c[0] + c[1] for _, _, c in titan)
        L = [f"HOMEWORK — {a['name']} (every pillar)", "", f"Updated {stamp or '{stamp}'}. {n} open across {len({x[0]['id'] for x in items})} pillars.", "",
             "When Joseph asks 'do you have homework?', this page is the answer. Read it top to bottom and start on number 1 without asking. "
             "When one is done, start the next. Rules for every pillar: https://github.com/jpavia10/prometheus-hub/blob/main/AI_START_HERE.md "
             "(read it once per session). Save every file in the pillar's Drive folder 'incoming (AI drop files)' under the exact name given; never in the chat, never for Joseph to copy.", ""]
        if titan:
            for p, _, c in titan:
                L += [f"TITAN RELIQUARY (its own loop, the exception): {c[0]} homework sheets + {c[1]} projects. Open the Drive doc 'Titan Reliquary/WORK QUEUE for {a['name']}' "
                      f"(newest: https://raw.githubusercontent.com/jpavia10/titan-reliquary-preview/main/docs/agents/QUEUE_{a['id']}.md) and follow its own order. Do Titan's sheets that are due first, then the list below by due date.", ""]
        L += ["IN THIS ORDER:"]
        for i, (p, t, _) in enumerate(work, 1):
            L += [f"{i}. [{p['name']}] {t['id']} · {t['title']} · due {t.get('due')}" + (" · waits for its input file" if t.get("state") == "next" else "")]
        L += [""]
        for i, (p, t, _) in enumerate(work, 1):
            L += [f"==================== {i}. {p['name'].upper()} ===================="] + task_md(i, t, p, "")
        out[os.path.join(HUB, "docs", "agents", "drive", f"HOMEWORK_{a['id']}.txt")] = "\n".join(L).rstrip() + "\n"

    # the board
    ais = reg["ais"] + [{"id": "claude", "name": "Claude"}]
    B = [GEN, "", "# Homework board: every pillar, every AI", "", f"Updated {stamp or '{stamp}'}. Open tasks (now + next). Titan counts its homework sheets + projects.", "",
         "| Pillar | State | " + " | ".join(a["name"] for a in ais) + " |", "|---|---|" + "---|" * len(ais)]
    for r in board["pillars"]:
        cells = [("—" if r["open"].get(a["id"]) in (None, 0) else str(r["open"][a["id"]])) for a in ais]
        B.append(f"| {r['name']} | {r['state']} | " + " | ".join(cells) + " |")
    B += ["", "Each AI's full list, every pillar on one page: Drive 'Prometheus Hub/{AI folder}/HOMEWORK — {Name} (every pillar)' (text in docs/agents/drive/HOMEWORK_{ai}.txt)."]
    out[os.path.join(HUB, "HOMEWORK.md")] = "\n".join(B) + "\n"
    board["updated"] = stamp
    out[os.path.join(HUB, "data", "board.json")] = json.dumps(board, indent=1, ensure_ascii=False) + "\n"
    deadlines.sort(key=lambda d: (d["due"] or "9", d["pillar"], d["id"]))
    out[os.path.join(HUB, "data", "deadlines.json")] = json.dumps({"updated": stamp, "tasks": deadlines}, indent=1, ensure_ascii=False) + "\n"

    stale = []
    for path, text in out.items():
        if check:
            try:
                old = open(path, encoding="utf-8").read()
            except FileNotFoundError:
                stale.append(path); continue
            norm = lambda s: re.sub(r"\d{4}-\d\d-\d\d \d\d:\d\d UTC", "{stamp}", s).replace('"updated": null', '"updated": "{stamp}"')
            if norm(old) != norm(text):
                stale.append(path)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    if check:
        for s in stale: print("out of date:", s)
        return 1 if stale else 0
    print(f"wrote {len(out)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
