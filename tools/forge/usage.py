#!/usr/bin/env python3
"""What became of every task the AIs were given (owner, 2026-11-25: "we assign a lot but you dont use it all ... so I can gauge what
is actually already done and its current state").

Reads every queue (pillars/*/docs/agents/queues.json and docs/agents/queues.json) and sorts each task into one state:
  open      : assigned, not delivered yet (now / next)
  used      : delivered, and its file or task id appears in the shipped site (pillars/, deck/, kit/, art/, data/)
  check     : delivered second read or audit by one AI of another's file; its use is the verdict it gave
  design    : delivered plan, spec or audit that shaped a build rather than shipping as data
  waiting   : delivered data that waits for a second read before it is shown
  unused    : delivered, accepted, and not used anywhere yet (the backlog to wire)
  dropped   : withdrawn or parked
Writes docs/agents/usage.json (one row per task) and prints the totals.  python3 tools/forge/usage.py [--check]
"""
import json, glob, os, re, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHIP = ["pillars", "deck", "kit", "art", "data"]
OUT = os.path.join(ROOT, "docs", "agents", "usage.json")

def shipped_text():
    parts = []
    for root in SHIP:
        for dp, dn, fn in os.walk(os.path.join(ROOT, root)):
            if "/docs" in dp or "/collaborators" in dp: continue
            for f in fn:
                if f.endswith((".js", ".json", ".html", ".css")) and f != "queues.json":
                    try: parts.append(open(os.path.join(dp, f), errors="ignore").read())
                    except OSError: pass
    return "\n".join(parts)

DESIGN = re.compile(r"(?i)function spec|build plan|data shape|motion spec|particle|icon|audit|a11y|accessib|recheck|painting focus|realm labels|done markers|checker|features the best|apps taken apart|teardown|mood|palette")
CHECK = re.compile(r"(?i)second read|second reader|second-read|blind (second )?(read|transcription)|re-read your audit|third reader|arbitrat")
WAIT = re.compile(r"(?i)not second-read|second read pending|waits? for (its|a|the) (second read|check)|HUB-MUS-0\d|before (it is|any is) (built|wired|shown)|when it is wired|joins? the tree")

def classify(t, ai, used):
    st = t.get("state")
    if st in ("withdrawn", "parked"): return "dropped"
    if st in ("now", "next"): return "open"
    if used: return "used"
    title, rev = t.get("title", ""), t.get("review") or ""
    if ai != "gemini" and CHECK.search(title + " " + t.get("id", "")) or re.search(r"-MUS-|-GRK-", t.get("id", "")) and CHECK.search(title): return "check"
    if CHECK.search(title): return "check"
    if DESIGN.search(title): return "design"
    if WAIT.search(rev): return "waiting"
    return "unused"

def main(argv):
    B = shipped_text(); rows = []
    for q in sorted(glob.glob(os.path.join(ROOT, "pillars/*/docs/agents/queues.json"))) + [os.path.join(ROOT, "docs/agents/queues.json")]:
        pillar = q.split(os.sep)[-4] if "/pillars/" in q else "hub"
        for a in json.load(open(q)).get("agents", []):
            for t in a.get("tasks", []):
                stem = re.sub(r"_?\{YYYYMMDD-HHMM\}.*$", "", (t.get("deliver") or {}).get("file", ""))
                used = bool(stem and stem in B) or t["id"] in B
                rows.append({"pillar": pillar, "ai": a["id"], "id": t["id"], "title": t.get("title", ""), "due": t.get("due"), "closed": t.get("closed"),
                             "state": classify(t, a["id"], used), "file": stem, "review": (t.get("review") or "")[:400]})
    rows.sort(key=lambda r: (r["pillar"], r["state"], r["id"]))
    tot = collections.Counter(r["state"] for r in rows)
    doc = {"about": "Generated by tools/forge/usage.py: what became of every task given to an AI. States: open, used, check, design, waiting, unused, dropped.",
           "totals": dict(tot), "rows": rows}
    text = json.dumps(doc, ensure_ascii=False, indent=1) + "\n"
    cur = open(OUT).read() if os.path.exists(OUT) else ""
    if "--check" in argv:
        print("usage: " + ("up to date" if cur == text else "out of date")); return 0 if cur == text else 1
    if cur != text: open(OUT, "w").write(text)
    print("usage:", ", ".join(f"{k} {v}" for k, v in tot.most_common()), f"({len(rows)} tasks)")
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv))
