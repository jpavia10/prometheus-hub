/* World history for every pillar (Claude, 2026-11-24; owner: "use it as a dataset for other pillars ... no reason to generate it").
   Reads window.PK_HISTORY (pillars/athenaeum/data/world-history.js, generated by tools/history/build.py from world-history.json).
   PKHistory.regionsOf(placeNames) -> region slugs; PKHistory.forRegions(regions, fromYear, toYear) -> [{ e, w, text }] where w is how
   close the entry is: 2 a named region (Lithuania, Malta, Michigan ...), 1 the United States, 0 the world. */
(function () {
  var REG = [[/lithuan|tel[sš]i|samogit|kaunas|vilnius|tryškiai|tryskiai/i, "lithuania"], [/\bmalta\b|maltese|valletta|gozo/i, "malta"], [/detroit|michigan|wayne county|oakland county|holly/i, "michigan"],
    [/brooklyn|new york|kings county|manhattan|ellis island/i, "new-york"], [/boston|massachusetts|camp devens/i, "massachusetts"], [/tennessee/i, "tennessee"],
    [/north carolina/i, "north-carolina"], [/south carolina/i, "south-carolina"], [/virginia/i, "virginia"], [/pennsylvania|chester county/i, "pennsylvania"],
    [/england|london|kent|yorkshire|leicester|liverpool/i, "england"], [/ontario|canada|algoma/i, "canada"], [/france|langres|chaumont/i, "france"], [/germany|hamburg/i, "germany"],
    [/\bohio\b|columbus barracks/i, "ohio"], [/california|frazier park|kern/i, "california"], [/philippines|manila/i, "philippines"], [/cherokee/i, "cherokee-nation"]];
  var US = { "michigan": 1, "new-york": 1, "massachusetts": 1, "tennessee": 1, "north-carolina": 1, "south-carolina": 1, "virginia": 1, "pennsylvania": 1, "ohio": 1, "california": 1, "georgia": 1 };
  function year(d) { var m = /^(-?\d{1,4})/.exec(String(d || "")); return m ? +m[1] : null; }
  window.PKHistory = {
    year: year,
    all: function () { return (window.PK_HISTORY && window.PK_HISTORY.entries) || []; },
    regionsOf: function (names) {
      var out = {}; (names || []).forEach(function (n) { REG.forEach(function (r) { if (r[0].test(String(n || ""))) out[r[1]] = 1; }); });
      if (Object.keys(out).some(function (r) { return US[r]; })) { out["united-states"] = 1; out["american-colonies"] = 1; }
      return Object.keys(out);
    },
    forRegions: function (regions, from, to) {
      var set = {}; (regions || []).forEach(function (r) { set[r] = 1; });
      return this.all().map(function (e) {
        var y = year(e.date); if (y == null || y < from || y > to) return null;
        var w = -1; (e.regions || []).forEach(function (r) { var v = r === "world" ? 0 : (r === "united-states" || r === "american-colonies") ? (set[r] ? 1 : -1) : (set[r] ? 2 : -1); if (v > w) w = v; });
        if (w < 0) return null;
        var loc = (e.local || []).filter(function (l) { return (l.regions || []).some(function (r) { return set[r]; }); })[0];
        return { e: e, w: w, text: loc ? loc.text : e.text };
      }).filter(Boolean);
    }
  };
})();
